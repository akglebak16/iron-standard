// One schema for GDScript storage and the engine-independent native kernel.
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const schema = JSON.parse(fs.readFileSync(path.join(root,'tools/battle/unit_columns.json'),'utf8'));
const groups = {real:schema.real,integer:[...schema.integer,'mode'],vector:schema.vector};
const write = (name,text) => {
 const file=path.join(root,name);
 if(process.argv.includes('--check')) {
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==text) throw Error(`Stale unit schema output: ${name}`);
 } else { fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text); }
};
let gd='extends "res://runtime/simulation/motion_store.gd"\n## Generated layout; values are authoritative for bound units.\n';
let h='#pragma once\n// Generated by tools/battle/unit_columns.cjs.\nnamespace iron::battle {\n';
for(const [kind,fields] of Object.entries(groups)) {
 const prefix=kind[0].toUpperCase();
 gd+=`enum ${prefix} { ${fields.map(n=>n.toUpperCase()).join(', ')}, COUNT }\n`;
 h+=`enum ${prefix} { ${fields.map(n=>prefix+'_'+n.toUpperCase()).join(', ')}, ${prefix}_COUNT };\n`;
}
gd+='const MODES = '+JSON.stringify(schema.modes)+'\n';
h+='enum Mode { UNASSIGNED, SLOT, MELEE, SHOOT, SHOOT_SLOT, SKIRMISH, RANK, BRACE, FALLBACK };\n}\n';
gd+=`var capacity := 0
var real_fields := PackedFloat64Array()
var integer_fields := PackedInt64Array()
var vector_fields := PackedVector2Array()

func resize(count: int) -> void:
	super.resize(count)
	if count <= capacity: return
	var grown := maxi(16, capacity * 2)
	while grown < count: grown *= 2
	var reals := PackedFloat64Array()
	var integers := PackedInt64Array()
	var vectors := PackedVector2Array()
	reals.resize(grown * R.COUNT)
	integers.resize(grown * I.COUNT)
	vectors.resize(grown * V.COUNT)
	for field in R.COUNT:
		for row in capacity: reals[field * grown + row] = real_fields[field * capacity + row]
	for field in I.COUNT:
		for row in capacity: integers[field * grown + row] = integer_fields[field * capacity + row]
	for field in V.COUNT:
		for row in capacity: vectors[field * grown + row] = vector_fields[field * capacity + row]
	real_fields = reals
	integer_fields = integers
	vector_fields = vectors
	capacity = grown

func copy_row(source: int, destination: int) -> void:
	super.copy_row(source, destination)
	for field in R.COUNT: real_fields[field * capacity + destination] = real_fields[field * capacity + source]
	for field in I.COUNT: integer_fields[field * capacity + destination] = integer_fields[field * capacity + source]
	for field in V.COUNT: vector_fields[field * capacity + destination] = vector_fields[field * capacity + source]
`;
write('core/battle/model/unit_columns.gd',gd);
write('core/battle/simulation/native/unit_columns.hpp',h);
write('core/battle/simulation/native/movement_parameters.hpp', '#pragma once\nnamespace iron::battle { enum Parameter { '+schema.parameters.join(', ')+', PARAMETER_COUNT }; }\n');
write('core/battle/api/movement_parameters.gd','extends RefCounted\nconst Config = preload("res://core/battle/config.gd")\nstatic func values() -> PackedFloat64Array:\n\treturn PackedFloat64Array(['+schema.parameters.map(n=>'Config.'+n).join(', ')+'])\n');
console.log('Unit column schema checked');
