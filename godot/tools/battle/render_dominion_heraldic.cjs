// Atlas assembly only: generated drawings are preserved in heraldic_source/.
// NODE_PATH may point to the bundled runtime's node_modules (sharp).
const fs=require('fs'),path=require('path'),sharp=require('sharp');
const dir=__dirname,output=path.resolve(dir,'../../apps/godot/visuals/assets');
const W=152,H=176,ids=['d1','d2','d3','d2s','d3s','d2x','d3x'];
async function cell(file,col,row,cols,rows){
 const meta=await sharp(file).metadata();
 const x=Math.round(col*meta.width/cols),y=Math.round(row*meta.height/rows);
 const width=Math.round((col+1)*meta.width/cols)-x,height=Math.round((row+1)*meta.height/rows)-y;
 const {data,info}=await sharp(file).extract({left:x,top:y,width,height}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let left=width,top=height,right=0,bottom=0;
 for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(data[(y*width+x)*4+3]>40){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
 if(right<=left)throw Error('Empty source cell');
 return sharp(data,{raw:info}).extract({left,top,width:right-left+1,height:bottom-top+1}).png().toBuffer();
}
async function stamp(buffer,width,height,left,top){
 const sprite=await sharp(buffer).resize(width,height,{fit:'fill'}).png().toBuffer();
 return {input:sprite,left,top};
}
async function frame(overlays){return sharp({create:{width:W,height:H,channels:4,background:'#00000000'}}).composite(overlays).png().toBuffer();}
async function raw(buffer){return sharp(buffer).ensureAlpha().raw().toBuffer();}
function png(data){return sharp(data,{raw:{width:W,height:H,channels:4}}).png().toBuffer();}
// Head cut: a bowl symmetric about the shared neck joint, so the head (mirrored back to face
// forward) fills exactly the hole it leaves in the torso: no gaps, no overlaps.
function bowl(spec){
 const xs=spec.head_polygon.map(p=>Math.abs(p[0]-spec.neck[0]));
 const top=Math.max(...xs);
 const shoulders=Math.min(...spec.head_polygon.filter(p=>Math.abs(p[0]-spec.neck[0])>=top-1).map(p=>p[1]).filter(y=>y>20));
 const bottom=spec.head_polygon.filter(p=>p[1]>=spec.neck[1]-1).map(p=>Math.abs(p[0]-spec.neck[0]));
 const neck=Math.max(7,Math.min(11,bottom.length?Math.max(...bottom):9));
 return {top,shoulders:shoulders+(spec.neck[1]-shoulders)*.15,neck};
}
function inBowl(x,y,shape,joint){
 const dx=Math.abs(x+.5-joint[0]),cy=y+.5;
 if(cy>joint[1])return false;
 if(cy<=shape.shoulders)return dx<shape.top;
 const t=(cy-shape.shoulders)/(joint[1]-shape.shoulders);
 return dx<shape.neck+(shape.top-shape.neck)*Math.sqrt(Math.max(0,1-t*t));
}
// Keeps only pieces of at least `min` pixels (8-connected); returns the cleaned buffer.
function dropSpecks(data,min,keepLargest){
 // Near-invisible haze (alpha < 12) only links specks to the figure; clear it first.
 for(let p=0;p<data.length;p+=4)if(data[p+3]<12)data.fill(0,p,p+4);
 const seen=new Int32Array(W*H).fill(-1),groups=[];
 for(let start=0;start<W*H;start++){
  if(seen[start]>=0||data[start*4+3]===0)continue;
  const stack=[start],members=[];seen[start]=groups.length;
  while(stack.length){const i=stack.pop();members.push(i);const x=i%W,y=(i/W)|0;
   for(let oy=-1;oy<=1;oy++)for(let ox=-1;ox<=1;ox++){const nx=x+ox,ny=y+oy;if(nx<0||ny<0||nx>=W||ny>=H)continue;const j=ny*W+nx;
    if(seen[j]<0&&data[j*4+3]>0){seen[j]=groups.length;stack.push(j);}}}
  groups.push(members);
 }
 const largest=groups.reduce((a,g)=>Math.max(a,g.length),0);
 for(const g of groups)if(g.length<min||(keepLargest&&g.length<largest*.05))for(const i of g)data.fill(0,i*4,i*4+4);
 return data;
}
async function main(){
 const heads=JSON.parse(fs.readFileSync(path.join(dir,'heraldic_source/head-layout.json'),'utf8'));
 const neckJoint=[76,78];
 const headData=Object.fromEntries(ids.map(id=>[id,{center:[76,heads[id].center[1]+neckJoint[1]-heads[id].neck[1]],neck:neckJoint,canonical_facing:1}]));
 fs.writeFileSync(path.join(output,'../dominion_heraldic_heads.gd'),'extends RefCounted\n## Generated by tools/battle/render_dominion_heraldic.cjs from head-layout.json.\nconst DATA = '+JSON.stringify(headData,null,'\t')+'\n');
 const neckCap=await sharp(path.join(dir,'heraldic_source/neck_cap.svg')).png().toBuffer();
 const bodies=[],weapons=[],gloves=[];
 for(let i=0;i<7;i++)bodies.push(await cell(path.join(dir,'heraldic_source/body.png'),i%3,Math.floor(i/3),3,3));
 for(let i=0;i<5;i++)weapons.push(await cell(path.join(dir,'heraldic_source/weapons.png'),i%2,Math.floor(i/2),2,3));
 for(let i=0;i<4;i++)gloves.push(await cell(path.join(dir,'heraldic_source/gloves.png'),i%2,Math.floor(i/2),2,2));
 const config=[{w:1,h:80,y:48,grip:.15},{w:0,h:102,y:28,grip:.5},{w:0,h:102,y:28,grip:.5},{w:2,h:146,y:3,grip:.5},{w:3,h:146,y:3,grip:.4},{w:4,h:63,y:88,grip:.31},{w:4,h:63,y:88,grip:.31}];
 for(let variant=0;variant<4;variant++){
  const overlays=[];
  for(let i=0;i<7;i++){
   let sprite=await sharp(bodies[i]).resize(116,140).png().toBuffer();
   // Shields belong on the non-weapon side. All source busts are mirrored consistently.
   if(i<4)sprite=await sharp(sprite).flop().png().toBuffer();
   // The whole bust moves so its neck sits on the shared joint; head and torso stay together.
   const spec=heads[ids[i]],shiftX=neckJoint[0]-spec.neck[0],shiftY=neckJoint[1]-spec.neck[1];
   let body=await raw(await frame([{input:sprite,left:18+shiftX,top:18+shiftY}]));
   // Four subtle complexion variants, preserving the selected silhouette/equipment.
   for(let y=20;y<88;y++)for(let x=36;x<116;x++){
    const p=(y*W+x)*4,r=body[p],g=body[p+1],b=body[p+2];
    if(body[p+3]>0 && r>g*1.17 && g>b*1.12){const k=[1,.92,1.035,.97][variant];for(let c=0;c<3;c++)body[p+c]=Math.min(255,Math.round(body[p+c]*k));}
   }
   // One cut line for both parts: the head keeps everything inside the bowl, the torso the rest.
   const shape=bowl(spec),head=Buffer.alloc(W*H*4);
   let torso=Buffer.from(body);
   for(let y=0;y<H;y++)for(let x=0;x<W;x++)if(inBowl(x,y,shape,neckJoint)){
    const p=(y*W+x)*4;
    // Mirrored about the joint, the bowl maps onto itself.
    const targetX=spec.mirror?2*neckJoint[0]-1-x:x;
    body.copy(head,(y*W+targetX)*4,p,p+4);
    torso[p+3]=0;
   }
   dropSpecks(head,1,true);
   dropSpecks(torso,24,false);
   body=await raw(await frame([{input:await png(torso),left:0,top:0},{input:await png(head),left:0,top:0}]));
   const cap=Math.round(shape.neck*2+2);
   const headless=await raw(await frame([{input:await png(torso),left:0,top:0},await stamp(neckCap,cap,6,neckJoint[0]-cap/2|0,neckJoint[1]-4)]));
   const c=config[i],meta=await sharp(weapons[c.w]).metadata();
   const width=Math.round(c.h*meta.width/meta.height);
   const left=c.w===4?72:Math.min(125-Math.round(width*c.grip),W-width-2);
   const handX=c.w===4?96:left+Math.round(width*c.grip);
   const weaponStamp=await stamp(weapons[c.w],width,c.h,left,c.y);
   const moving=[];
   // Hand-only dorsal mittens: no forearm/cuff and no separated fingers.
   const steel=[1,2,4,6].includes(i);
   const grip=gloves[steel?0:1];
   if(c.w===4){
    const support=gloves[steel?2:3];
    // Rear fist wraps the trigger area; the other hand cradles the fore-end.
    // Both thumbs stay beside/below the rail, clear of the bolt and string path.
    moving.push(await stamp(grip,20,22,83,117));
    moving.push(await stamp(support,20,22,115,116));
    // Keep the bolt rail and string visible above the supporting fingers.
    moving.push(weaponStamp);
   }else{
    moving.push(weaponStamp);
    moving.push(await stamp(grip,20,22,handX-13,105));
    // All five melee skins, including the requested halberd pose, use one hand.
   }
   if(variant===0)console.log(ids[i], 'weapon pivot',handX,c.w===4?128:116);
   const weapon=await raw(await frame(moving));
   const portrait=await raw(await frame([{input:await png(body),left:0,top:0},{input:await png(weapon),left:0,top:0}]));
   const corpseHeadless=await frame([{input:await png(headless),left:0,top:0},{input:await png(weapon),left:0,top:0}]);
   const flash=Buffer.from(portrait);for(let p=0;p<flash.length;p+=4)flash[p]=flash[p+1]=flash[p+2]=255;
   const parts=[await png(body),await png(weapon),await png(portrait),await png(headless),await png(head),await png(flash),await png(portrait),corpseHeadless];
   for(let row=0;row<parts.length;row++)overlays.push({input:parts[row],left:i*W,top:row*H});
  }
  await sharp({create:{width:W*7,height:H*8,channels:4,background:'#00000000'}}).composite(overlays).png().toFile(path.join(output,`dominion_heraldic_${variant}.png`));
 }
 console.log('Built 4 Dominion atlases: 7 troops × 8 states, 152×176 frames');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
