// Enumerate visual resource edges so dynamic choices remain architecture-checkable.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const assets='apps/godot/visuals/assets';
const entries=fs.readdirSync(path.join(root,assets)).filter(n=>/\.(png|svg)$/.test(n)).sort();
const paths=Object.fromEntries(entries.map(n=>[n.replace(/\.[^.]+$/,''),`res://${assets}/${n}`]));
const output='extends RefCounted\n## Generated by tools/export_asset_paths.cjs; do not hand edit.\nconst PATHS = '+JSON.stringify(paths,null,'\t')+'\n\nstatic func path(key: String) -> String:\n\treturn PATHS.get(key, "")\n';
const file=path.join(root,'apps/godot/visuals/asset_paths.gd');
if(process.argv.includes('--check')) {
 if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==output)throw Error('Visual paths stale: run node godot/tools/export_asset_paths.cjs');
} else fs.writeFileSync(file,output);
console.log(`Visual resource paths checked: ${entries.length}`);
